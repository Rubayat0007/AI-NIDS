"""Run the frozen NIDS pipeline over real captured packets.

Generates benign loopback HTTP traffic, captures it with scapy, then feeds
the packets through the production path: detect_packets -> extract_flows ->
predict_features -> aggregate_detection_results.

Limits, stated up front:
- The traffic is loopback and generated by this script, so every flow is
  benign by construction. This checks plumbing and output shape; it says
  nothing about detection quality or live-domain performance.
"""

from __future__ import annotations

import socket
import sys
import threading
import time
import urllib.request
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from scapy.all import conf, get_if_list, sniff  # noqa: E402

from src.detection import aggregate_detection_results, detect_packets  # noqa: E402
from src.inference import load_model  # noqa: E402

PORT = 8099
REQUESTS = 8


def serve(stop: threading.Event):
    server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    server.bind(("127.0.0.1", PORT))
    server.listen(8)
    server.settimeout(1.0)

    while not stop.is_set():
        try:
            connection, _ = server.accept()
            connection.recv(2048)
            connection.sendall(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\nok")
            connection.close()
        except Exception:
            continue

    server.close()


def main() -> int:
    model = load_model()

    loopback = [name for name in get_if_list() if "loopback" in name.lower()]
    interface = loopback[0] if loopback else conf.iface
    print(f"interface: {interface}")

    stop = threading.Event()
    threading.Thread(target=serve, args=(stop,), daemon=True).start()
    time.sleep(0.5)

    def drive():
        time.sleep(1.0)
        for _ in range(REQUESTS):
            try:
                urllib.request.urlopen(f"http://127.0.0.1:{PORT}/data", timeout=2).read()
            except Exception:
                pass
            time.sleep(0.15)

    threading.Thread(target=drive, daemon=True).start()

    started = time.monotonic()
    packets = sniff(iface=interface, filter=f"tcp port {PORT}", timeout=8, count=400)
    duration = round(time.monotonic() - started, 3)
    stop.set()

    print(f"captured: {len(packets)} packets over {duration}s")

    if not packets:
        print("ERROR: no packets captured", file=sys.stderr)
        return 2

    detection = detect_packets(model, packets, capture_duration=duration)
    aggregate = aggregate_detection_results(detection)

    print(f"flows extracted: {len(detection['flows'])}")
    for index, flow in enumerate(detection["flows"]):
        probabilities = [round(float(value), 4) for value in flow["probabilities"]]
        print(
            f"  flow {index}: prediction={flow['prediction']} "
            f"p_benign/p_attack={probabilities} packets={flow['packet_count']}"
        )

    print(
        f"aggregate: prediction={aggregate['prediction']} "
        f"attack_probability={aggregate['attack_probability']:.4f} "
        f"severity={aggregate['severity']} packets={aggregate['packet_count']}"
    )
    print(
        "NOTE: loopback traffic generated locally; every flow is benign by "
        "construction. This validates plumbing, not detection quality."
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
