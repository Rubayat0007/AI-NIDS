"""Does a model trained on live-captured scenarios separate them?

Design decisions that keep this honest:

- The unit of splitting is the *capture run*, not the flow. Flows from one run
  share timing and background, so a flow-level split would leak.
- The frozen CICIDS model is evaluated on the same held-out runs, so the
  comparison is direct.
- The candidate is an experiment. It is saved with its digest and reported,
  never wired into production.

Scope: loopback scenarios generated by this script. A candidate that separates
them proves the harness works, not that it detects attacks in a real network.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import socket
import sys
import threading
import time
import urllib.request
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

import joblib  # noqa: E402
import numpy as np  # noqa: E402
from scapy.all import conf, get_if_list, sniff  # noqa: E402
from sklearn.ensemble import RandomForestClassifier  # noqa: E402

from src.evaluation.scenario_metrics import metrics  # noqa: E402
from src.features.flow import extract_flows  # noqa: E402
from src.features.schema import FEATURE_NAMES  # noqa: E402
from src.inference import load_model, predict_features  # noqa: E402

HTTP_PORT = 8089
RUNS_PER_SCENARIO = 6
TRAIN_RUNS = 4
SCAN_BASE = 8200
FLOOD_BASE = 8300


def start_server(stop, port):
    server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    server.bind(("127.0.0.1", port))
    server.listen(16)
    server.settimeout(0.4)

    while not stop.is_set():
        try:
            connection, _ = server.accept()
            connection.recv(1024)
            connection.sendall(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\nok")
            connection.close()
        except Exception:
            continue

    server.close()


def benign(run):
    for _ in range(5 + run):
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{HTTP_PORT}/x", timeout=2).read()
        except Exception:
            pass
        time.sleep(0.08)


def scan(run):
    base = SCAN_BASE + run * 20
    for offset in range(6 + run):
        client = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        client.settimeout(0.2)
        try:
            client.connect_ex(("127.0.0.1", base + offset))
        finally:
            client.close()
        time.sleep(0.03)


def flood(run):
    port = FLOOD_BASE + run
    for _ in range(60 + run * 20):
        client = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        client.settimeout(0.05)
        try:
            client.connect_ex(("127.0.0.1", port))
        finally:
            client.close()


SCENARIOS = (("benign", benign, 0), ("scan", scan, 1), ("flood", flood, 1))


def capture_run(interface, generate, run):
    packets = []

    def listen():
        packets.extend(sniff(iface=interface, filter="tcp", timeout=3, count=800))

    thread = threading.Thread(target=listen)
    thread.start()
    time.sleep(0.3)
    generate(run)
    thread.join()
    return packets


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path,
                        default=PROJECT_ROOT / "results" / "live_adaptation")
    parser.add_argument("--models-dir", type=Path,
                        default=PROJECT_ROOT / "src" / "models")
    args = parser.parse_args()

    frozen = load_model()
    loopback = [name for name in get_if_list() if "loopback" in name.lower()]
    interface = loopback[0] if loopback else conf.iface
    print(f"interface: {interface}")

    stop = threading.Event()
    threading.Thread(target=start_server, args=(stop, HTTP_PORT), daemon=True).start()
    time.sleep(0.4)

    samples = []

    for name, generate, label in SCENARIOS:
        for run in range(RUNS_PER_SCENARIO):
            packets = capture_run(interface, generate, run)
            flows = extract_flows(packets)
            for features in flows:
                samples.append({
                    "scenario": name,
                    "label": label,
                    "run": run,
                    "split": "train" if run < TRAIN_RUNS else "test",
                    "features": {key: float(features[key]) for key in FEATURE_NAMES},
                })
            print(f"{name:7} run {run}: packets={len(packets):4} flows={len(flows):3}")

    stop.set()

    train = [row for row in samples if row["split"] == "train"]
    test = [row for row in samples if row["split"] == "test"]

    if not train or not test:
        print("ERROR: empty train or test partition", file=sys.stderr)
        return 2

    X_train = np.array([[row["features"][name] for name in FEATURE_NAMES] for row in train])
    y_train = np.array([row["label"] for row in train])
    X_test = np.array([[row["features"][name] for name in FEATURE_NAMES] for row in test])
    y_test = np.array([row["label"] for row in test])

    candidate = RandomForestClassifier(
        n_estimators=200, class_weight="balanced", random_state=42, n_jobs=1
    ).fit(X_train, y_train)

    candidate_predictions = candidate.predict(X_test).tolist()
    frozen_predictions = []

    for row in test:
        probabilities = predict_features(frozen, row["features"])
        frozen_predictions.append(int(probabilities["prediction"]))

    candidate_metrics = metrics(list(zip(y_test.tolist(), candidate_predictions)))
    frozen_metrics = metrics(list(zip(y_test.tolist(), frozen_predictions)))

    args.models_dir.mkdir(parents=True, exist_ok=True)
    candidate_path = args.models_dir / "nids_live_candidate.pkl"
    joblib.dump(candidate, candidate_path)
    digest = hashlib.sha256(candidate_path.read_bytes()).hexdigest().upper()

    summary = {
        "interface": interface,
        "runs_per_scenario": RUNS_PER_SCENARIO,
        "train_runs_per_scenario": TRAIN_RUNS,
        "split": "by run; flows from one run never straddle train/test",
        "counts": {
            "train": len(train),
            "test": len(test),
            "attack_train": int(y_train.sum()),
            "attack_test": int(y_test.sum()),
        },
        "candidate": {"metrics": candidate_metrics, "path": str(candidate_path), "sha256": digest},
        "frozen_cicids": {"metrics": frozen_metrics},
        "note": ("Loopback scenarios only. Candidate is an experiment, not a "
                 "production model; it is not wired into src/config.py."),
    }

    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    lines = [
        "# Live-domain adaptation experiment",
        "",
        f"Runs: {RUNS_PER_SCENARIO} per scenario, {TRAIN_RUNS} for training, "
        f"{RUNS_PER_SCENARIO - TRAIN_RUNS} held out. Split by run, not by flow.",
        "",
        f"Train flows {len(train)} ({int(y_train.sum())} attack) | "
        f"test flows {len(test)} ({int(y_test.sum())} attack)",
        "",
        "| Metric | Candidate (live scenarios) | Frozen CICIDS model |",
        "|---|---|---|",
    ]

    for key in ("accuracy", "precision", "recall", "f1", "false_positive_rate"):
        lines.append(
            f"| {key} | {candidate_metrics[key]:.4f} | {frozen_metrics[key]:.4f} |"
        )

    lines += [
        "",
        f"Candidate digest: `{digest}`",
        "",
        "## Reading this",
        "",
        "- The candidate was trained on generated loopback scenarios and tested on",
        "  held-out runs of the same generator. It shows the features are separable,",
        "  not that the model detects real attacks.",
        "- The frozen model's numbers on the same rows quantify the transfer gap.",
        "- Both classes are synthetic. A real deployment needs real labelled traffic;",
        "  nothing here changes the live-inference decision.",
    ]

    report_dir = PROJECT_ROOT / "docs" / "measurements"
    report_dir.mkdir(parents=True, exist_ok=True)
    (report_dir / "live-adaptation-2026-10-24.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )

    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
