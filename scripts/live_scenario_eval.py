"""Detect output on live-generated attack scenarios.

Generates three scenarios against loopback, captures each with scapy, labels
every flow by construction, and runs the frozen model on the extracted
features.

Scope limit, stated in the output: loopback traffic generated by this script
is not representative of a production network. This measures behaviour on
these scenarios; it does not authorise live inference.
"""

from __future__ import annotations

import argparse
import json
import socket
import sys
import threading
import time
import urllib.request
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from scapy.all import conf, get_if_list, sniff  # noqa: E402

from src.evaluation.scenario_metrics import metrics  # noqa: E402
from src.features.flow import extract_flows  # noqa: E402
from src.inference import load_model, predict_features  # noqa: E402

HTTP_PORT = 8089
SCAN_PORTS = (8100, 8101, 8102, 8103, 8104, 8105, 8106, 8107)
FLOOD_PORT = 8130


def start_server(stop: threading.Event):
    server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    server.bind(("127.0.0.1", HTTP_PORT))
    server.listen(16)
    server.settimeout(0.5)

    while not stop.is_set():
        try:
            connection, _ = server.accept()
            connection.recv(1024)
            connection.sendall(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\nok")
            connection.close()
        except Exception:
            continue

    server.close()


def benign_traffic():
    for _ in range(6):
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{HTTP_PORT}/x", timeout=2).read()
        except Exception:
            pass
        time.sleep(0.1)


def scan_traffic():
    for port in SCAN_PORTS:
        client = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        client.settimeout(0.2)
        try:
            client.connect_ex(("127.0.0.1", port))
        finally:
            client.close()
        time.sleep(0.05)


def flood_traffic():
    for _ in range(120):
        client = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        client.settimeout(0.05)
        try:
            client.connect_ex(("127.0.0.1", FLOOD_PORT))
        finally:
            client.close()


def capture(interface, generate):
    packets = []

    def listen():
        packets.extend(
            sniff(iface=interface, filter=f"tcp and portrange {HTTP_PORT}-{FLOOD_PORT}",
                  timeout=4, count=600)
        )

    thread = threading.Thread(target=listen)
    thread.start()
    time.sleep(0.4)
    generate()
    thread.join()
    return packets


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=PROJECT_ROOT / "results" / "live_scenarios.json")
    args = parser.parse_args()

    model = load_model()
    loopback = [name for name in get_if_list() if "loopback" in name.lower()]
    interface = loopback[0] if loopback else conf.iface
    print(f"interface: {interface}")

    stop = threading.Event()
    threading.Thread(target=start_server, args=(stop,), daemon=True).start()
    time.sleep(0.5)

    scenarios = [
        ("benign-http", benign_traffic, 0),
        ("port-scan", scan_traffic, 1),
        ("syn-flood", flood_traffic, 1),
    ]

    rows = []
    report = []

    for name, generate, label in scenarios:
        packets = capture(interface, generate)
        flows = extract_flows(packets)
        predictions = [predict_features(model, flow)["prediction"] for flow in flows]
        rows.extend((label, prediction) for prediction in predictions)
        report.append({
            "scenario": name,
            "label": "attack" if label else "benign",
            "packets": len(packets),
            "flows": len(flows),
            "predicted_attack": sum(predictions),
        })
        print(f"{name:12} packets={len(packets):4} flows={len(flows):3} "
              f"predicted_attack={sum(predictions)}")

    stop.set()

    summary = metrics(rows)

    output = {
        "interface": interface,
        "scenarios": report,
        "metrics": summary,
        "note": ("Loopback traffic generated locally; every label comes from the "
                 "scenario, not from analyst adjudication. Not evidence of "
                 "production detection performance."),
    }

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(output, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    print(json.dumps(summary, indent=2, sort_keys=True))
    print("\nNOTE: loopback scenarios only; this does not authorise live inference.")
    print(f"report: {args.output}")

    if not rows:
        print("ERROR: no flows captured", file=sys.stderr)
        return 2

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
